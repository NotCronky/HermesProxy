    [Fact]
    public void RequiredCurrency_IsACurrencyObjective()
    {
        if (!WorldClient.IsCataLegacy)
            return;

        var harness = new LegacyHandlerHarness(recordClientPackets: true);
        harness.Deliver(Opcode.SMSG_QUERY_QUEST_INFO_RESPONSE, [0, 0, .. Convert.FromHexString(FunForTheLittleOnes)],
            harness.Client.HandleQueryQuestInfoResponse);
        var response = harness.ClientWire.Sent.Select(s => s.Packet).OfType<QueryQuestInfoResponse>().Single();

        Assert.Equal(29507u, response.QuestID);
        var objective = Assert.Single(response.Info.Objectives);
        Assert.Equal(QuestObjectiveType.Currency, objective.Type);
        Assert.Equal(393, objective.ObjectID);
        Assert.Equal(15, objective.Amount);
        Assert.Equal(-1, objective.StorageIndex);
    }
